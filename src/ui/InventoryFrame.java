    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String productText = txtProductId.getText().trim();
String warehouseText = txtWarehouseId.getText().trim();
String quantityText = txtQuantity.getText().trim();
String reorderText = txtReorderLevel.getText().trim();

if (productText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the Product ID."
    );

    txtProductId.requestFocus();
    return;
}

if (warehouseText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the Warehouse ID."
    );

    txtWarehouseId.requestFocus();
    return;
}

if (quantityText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the quantity."
    );

    txtQuantity.requestFocus();
    return;
}

if (reorderText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the reorder level."
    );

    txtReorderLevel.requestFocus();
    return;
}

try {

    int productId = Integer.parseInt(productText);
    int warehouseId = Integer.parseInt(warehouseText);
    int quantity = Integer.parseInt(quantityText);
    int reorderLevel = Integer.parseInt(reorderText);

    if (quantity < 0 || reorderLevel < 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Quantity and reorder level cannot be negative."
        );

        return;
    }

    boolean added = dao.InventoryDao.addInventory(
            productId,
            warehouseId,
            quantity,
            reorderLevel
    );

    if (added) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Inventory added successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblInventory.getModel();

        dao.InventoryDao.loadInventory(model);

        txtInventoryId.setText("");
        txtProductId.setText("");
        txtWarehouseId.setText("");
        txtQuantity.setText("");
        txtReorderLevel.setText("");

        txtProductId.requestFocus();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not add inventory.\n"
                + "Make sure the Product ID and Warehouse ID exist "
                + "and this product is not already in that warehouse.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Product ID, Warehouse ID, quantity and reorder level "
            + "must be whole numbers."
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

