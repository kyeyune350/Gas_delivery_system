    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        String idText = txtInventoryId.getText().trim();

if (idText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select an inventory record first."
    );

    return;
}

int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this inventory record?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

try {

    int inventoryId = Integer.parseInt(idText);

    boolean deleted =
            dao.InventoryDao.deleteInventory(inventoryId);

    if (deleted) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Inventory deleted successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblInventory.getModel();

        dao.InventoryDao.loadInventory(model);

        txtInventoryId.setText("");
        txtProductId.setText("");
        txtWarehouseId.setText("");
        txtQuantity.setText("");
        txtReorderLevel.setText("");

        tblInventory.clearSelection();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Inventory could not be deleted.",
                "Delete Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid inventory ID."
    );
}
    }//GEN-LAST:event_btnDeleteActionPerformed

