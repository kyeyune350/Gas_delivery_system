    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        String idText = txtCustomerId.getText().trim();
String name = txtName.getText().trim();
String phone = txtPhone.getText().trim();
String email = txtEmail.getText().trim();
String address = txtAddress.getText().trim();

if (idText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a customer first."
    );
    return;
}

if (name.isEmpty() || phone.isEmpty()
        || email.isEmpty() || address.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all customer fields."
    );
    return;
}

try {

    int customerId = Integer.parseInt(idText);

    boolean updated = dao.CustomerDao.updateCustomer(
            customerId,
            name,
            phone,
            email,
            address
    );

    if (updated) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Customer updated successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblCustomers.getModel();

        dao.CustomerDao.loadCustomers(model);

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Customer was not found.",
                "Update Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid customer ID."
    );
}
    }//GEN-LAST:event_btnUpdateActionPerformed

