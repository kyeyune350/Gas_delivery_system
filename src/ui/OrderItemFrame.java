    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
String search =
        javax.swing.JOptionPane.showInputDialog(
                this,
                "Enter Order Item ID, Order ID or Product ID:"
        );

if (search == null) {
    return;
}

search = search.trim();

if (search.isEmpty()) {
    return;
}

javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
        tblOrderItem.getModel();

dao.OrderItemDao.searchOrderItems(
        model,
        search
);
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        try {

    if (txtOrderItemId.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select an order item first."
        );
        return;
    }

    int orderItemId =
            Integer.parseInt(
                    txtOrderItemId.getText().trim()
            );

    int confirm =
            javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "Are you sure you want to delete this order item?",
                    "Confirm Delete",
                    javax.swing.JOptionPane.YES_NO_OPTION
            );

    if (confirm != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    boolean success =
            dao.OrderItemDao.deleteOrderItem(
                    orderItemId
            );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order item deleted successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblOrderItem.getModel();

        dao.OrderItemDao.loadOrderItems(model);

        txtOrderItemId.setText("");
        txtOrderId.setText("");
        txtProductId.setText("");
        txtQuantity.setText("");
        txtUnitPrice.setText("");
        txtSubtotal.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order item could not be deleted."
        );
    }

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
        
    }//GEN-LAST:event_btnDeleteActionPerformed

