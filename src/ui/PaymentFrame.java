    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (txtPaymentId.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a payment first."
    );
    return;
}

int answer = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this payment?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (answer == javax.swing.JOptionPane.YES_OPTION) {

    int paymentId =
            Integer.parseInt(txtPaymentId.getText().trim());

    if (dao.PaymentDao.deletePayment(paymentId)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Payment deleted successfully."
        );

        dao.PaymentDao.loadPayments(
                (javax.swing.table.DefaultTableModel)
                tblPayments.getModel()
        );

        txtPaymentId.setText("");
        txtOrderId.setText("");
        txtAmount.setText("");
        txtPaymentDate.setText("");
        txtPaymentMethod.setText("");
        txtStatus.setText("");
        txtReferenceNumber.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Payment could not be deleted."
        );
    }
}
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void txtSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSearchActionPerformed
        // TODO add your handling code here:
        String search = txtSearch.getText().trim();

javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
        tblPayments.getModel();

if (search.isEmpty()) {

    dao.PaymentDao.loadPayments(model);

} else {

    dao.PaymentDao.searchPayments(
            model,
            search
    );
}
    }//GEN-LAST:event_txtSearchActionPerformed

