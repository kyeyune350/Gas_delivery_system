    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String registrationNumber =
        txtRegistrationNumber.getText().trim();

String vehicleType =
        txtVehicleType.getText().trim();

String capacityText =
        txtCapacity.getText().trim();

String status =
        txtStatus.getText().trim();

if (registrationNumber.isEmpty()
        || vehicleType.isEmpty()
        || capacityText.isEmpty()
        || status.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields."
    );
    return;
}

try {

    int capacity = Integer.parseInt(capacityText);

    boolean success = dao.VehicleDao.addVehicle(
            registrationNumber,
            vehicleType,
            capacity,
            status
    );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Vehicle added successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblVehicles.getModel();

        dao.VehicleDao.loadVehicles(model);

        txtRegistrationNumber.setText("");
        txtVehicleType.setText("");
        txtCapacity.setText("");
        txtStatus.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Vehicle could not be added."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Capacity must be a number."
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void tblVehiclesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblVehiclesMouseClicked
        // TODO add your handling code here:
        int row = tblVehicles.getSelectedRow();

if (row >= 0) {

    txtVehicleId.setText(
            tblVehicles.getValueAt(row, 0).toString()
    );

    txtRegistrationNumber.setText(
            tblVehicles.getValueAt(row, 1).toString()
    );

    txtVehicleType.setText(
            tblVehicles.getValueAt(row, 2).toString()
    );

    txtCapacity.setText(
            tblVehicles.getValueAt(row, 3).toString()
    );

    txtStatus.setText(
            tblVehicles.getValueAt(row, 4).toString()
    );
}
    }//GEN-LAST:event_tblVehiclesMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (txtVehicleId.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a vehicle first."
    );
    return;
}

try {

    int vehicleId =
            Integer.parseInt(txtVehicleId.getText().trim());

    String registrationNumber =
            txtRegistrationNumber.getText().trim();

    String vehicleType =
            txtVehicleType.getText().trim();

    int capacity =
            Integer.parseInt(txtCapacity.getText().trim());

    String status =
            txtStatus.getText().trim();

    boolean success = dao.VehicleDao.updateVehicle(
            vehicleId,
            registrationNumber,
            vehicleType,
            capacity,
            status
    );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Vehicle updated successfully."
        );

        dao.VehicleDao.loadVehicles(
                (javax.swing.table.DefaultTableModel)
                tblVehicles.getModel()
        );

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Vehicle could not be updated."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "ID and capacity must be numbers."
    );
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (txtVehicleId.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a vehicle first."
    );
    return;
}

int answer = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this vehicle?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (answer == javax.swing.JOptionPane.YES_OPTION) {

    int vehicleId =
            Integer.parseInt(txtVehicleId.getText().trim());

    boolean success =
            dao.VehicleDao.deleteVehicle(vehicleId);

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Vehicle deleted successfully."
        );

        dao.VehicleDao.loadVehicles(
                (javax.swing.table.DefaultTableModel)
                tblVehicles.getModel()
        );

        txtVehicleId.setText("");
        txtRegistrationNumber.setText("");
        txtVehicleType.setText("");
        txtCapacity.setText("");
        txtStatus.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Vehicle could not be deleted."
        );
    }
}
    }//GEN-LAST:event_btnDeleteActionPerformed

