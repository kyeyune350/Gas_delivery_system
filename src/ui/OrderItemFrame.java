    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        try {

    int orderId =
            Integer.parseInt(txtOrderId.getText().trim());

    int productId =
            Integer.parseInt(txtProductId.getText().trim());

    int quantity =
            Integer.parseInt(txtQuantity.getText().trim());

    double unitPrice =
            Double.parseDouble(txtUnitPrice.getText().trim());

    if (quantity <= 0 || unitPrice < 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Quantity must be greater than 0 and price cannot be negative."
        );
        return;
    }

    boolean success =
            dao.OrderItemDao.addOrderItem(
                    orderId,
                    productId,
                    quantity,
                    unitPrice
            );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order item added successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblOrderItem.getModel();

        dao.OrderItemDao.loadOrderItems(model);

        txtOrderItemId.setText("");
        txtOrderId.setText("");
        txtProductId.setText("");
        txtQuantity.setText("");
        txtUnitPrice.setText("");
        txtSubtotal.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not add order item."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Order ID, Product ID, Quantity and Unit Price must be valid numbers."
    );

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

