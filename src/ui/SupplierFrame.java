    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String supplierName = txtSupplierName.getText().trim();
String phone = txtPhone.getText().trim();
String email = txtEmail.getText().trim();
String address = txtAddress.getText().trim();

if (supplierName.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter the supplier name."
    );
    txtSupplierName.requestFocus();
    return;
}

if (phone.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter the supplier phone."
    );
    txtPhone.requestFocus();
    return;
}

if (email.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter the supplier email."
    );
    txtEmail.requestFocus();
    return;
}

if (address.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter the supplier address."
    );
    txtAddress.requestFocus();
    return;
}

boolean added = dao.SupplierDao.addSupplier(
        supplierName,
        phone,
        email,
        address
);

if (added) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Supplier added successfully."
    );

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel)
            tblSuppliers.getModel();

    dao.SupplierDao.loadSuppliers(model);

    txtSupplierId.setText("");
    txtSupplierName.setText("");
    txtPhone.setText("");
    txtEmail.setText("");
    txtAddress.setText("");

    txtSupplierName.requestFocus();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Could not add supplier.\n"
            + "Check that the email is not already being used.",
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        String idText = txtSupplierId.getText().trim();
String supplierName = txtSupplierName.getText().trim();
String phone = txtPhone.getText().trim();
String email = txtEmail.getText().trim();
String address = txtAddress.getText().trim();

if (idText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a supplier first."
    );
    return;
}

if (supplierName.isEmpty()
        || phone.isEmpty()
        || email.isEmpty()
        || address.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all supplier fields."
    );
    return;
}

try {

    int supplierId = Integer.parseInt(idText);

    boolean updated = dao.SupplierDao.updateSupplier(
            supplierId,
            supplierName,
            phone,
            email,
            address
    );

    if (updated) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Supplier updated successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblSuppliers.getModel();

        dao.SupplierDao.loadSuppliers(model);

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Supplier was not found.",
                "Update Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid supplier ID."
    );
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        String idText = txtSupplierId.getText().trim();

if (idText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a supplier first."
    );
    return;
}

int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this supplier?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

try {

    int supplierId = Integer.parseInt(idText);

    boolean deleted =
            dao.SupplierDao.deleteSupplier(supplierId);

    if (deleted) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Supplier deleted successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblSuppliers.getModel();

        dao.SupplierDao.loadSuppliers(model);

        txtSupplierId.setText("");
        txtSupplierName.setText("");
        txtPhone.setText("");
        txtEmail.setText("");
        txtAddress.setText("");

        tblSuppliers.clearSelection();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Supplier could not be deleted.",
                "Delete Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid supplier ID."
    );
}
    }//GEN-LAST:event_btnDeleteActionPerformed

