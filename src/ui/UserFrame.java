    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        // TODO add your handling code here:
        try {

    String name =
            txtName.getText().trim();

    String username =
            txtUsername.getText().trim();

    String email =
            txtEmail.getText().trim();

    String phone =
            txtPhone.getText().trim();

    String password =
            new String(txtPassword.getPassword()).trim();

    String role =
            ComboRole.getSelectedItem().toString();

    String status =
            ComboStatus.getSelectedItem().toString();


    // =========================
    // CHECK EMPTY FIELDS
    // =========================

    if (name.isEmpty()
            || username.isEmpty()
            || email.isEmpty()
            || phone.isEmpty()
            || password.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please fill in all fields."
        );

        return;
    }


    // =========================
    // CREATE USER
    // =========================

    boolean success =
            dao.UsersDao.createUser(
                    name,
                    username,
                    email,
                    phone,
                    password,
                    role,
                    status
            );


    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Account created successfully!\n"
                + "You can now login."
        );

        // Clear the fields
        txtName.setText("");
        txtUsername.setText("");
        txtEmail.setText("");
        txtPhone.setText("");
        txtPassword.setText("");

        ComboRole.setSelectedItem("CUSTOMER");
        ComboStatus.setSelectedItem("ACTIVE");

        // Open Login
        LoginFrame login =
                new LoginFrame();

        login.setLocationRelativeTo(null);
        login.setVisible(true);

        this.dispose();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not create account.\n"
                + "Username or email may already exist.",
                "Registration Failed",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage(),
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnCreateActionPerformed

