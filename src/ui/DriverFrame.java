    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (txtDriverId.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a driver first."
    );
    return;
}

String name = txtName.getText().trim();
String phone = txtPhone.getText().trim();
String licenseNumber = txtLicenseNumber.getText().trim();
String status = txtStatus.getText().trim();

if (name.isEmpty()
        || phone.isEmpty()
        || licenseNumber.isEmpty()
        || status.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields."
    );
    return;
}

int driverId = Integer.parseInt(
        txtDriverId.getText().trim()
);

boolean success = dao.DriverDao.updateDriver(
        driverId,
        name,
        phone,
        licenseNumber,
        status
);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Driver updated successfully."
    );

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel)
            tblDrivers.getModel();

    dao.DriverDao.loadDrivers(model);

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Driver could not be updated."
    );
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void tblDriversMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDriversMouseClicked
        // TODO add your handling code here:
        int row = tblDrivers.getSelectedRow();

if (row >= 0) {

    txtDriverId.setText(
            tblDrivers.getValueAt(row, 0).toString()
    );

    txtName.setText(
            tblDrivers.getValueAt(row, 1).toString()
    );

    txtPhone.setText(
            tblDrivers.getValueAt(row, 2).toString()
    );

    txtLicenseNumber.setText(
            tblDrivers.getValueAt(row, 3).toString()
    );

    txtStatus.setText(
            tblDrivers.getValueAt(row, 4).toString()
    );
}
    }//GEN-LAST:event_tblDriversMouseClicked

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (txtDriverId.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a driver first."
    );
    return;
}

int answer = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this driver?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (answer != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

int driverId = Integer.parseInt(
        txtDriverId.getText().trim()
);

boolean success = dao.DriverDao.deleteDriver(driverId);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Driver deleted successfully."
    );

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel)
            tblDrivers.getModel();

    dao.DriverDao.loadDrivers(model);

    txtDriverId.setText("");
    txtName.setText("");
    txtPhone.setText("");
    txtLicenseNumber.setText("");
    txtStatus.setText("");

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Driver could not be deleted."
    );
}
    }//GEN-LAST:event_btnDeleteActionPerformed

