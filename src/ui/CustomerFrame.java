    private void btnSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_btnSearchKeyReleased
        // TODO add your handling code here:
     
    // Get the username entered
    String username = txtName.getText().trim();

    // Get the table model
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblCustomers.getModel();

    // Clear the table first
    model.setRowCount(0);

    if (username.isEmpty()) {
        // Show all customers only when search is empty
        dao.CustomerDao.loadCustomers(model);
    } else {
        // Show only the matching username
        dao.CustomerDao.searchCustomers(username, model);
    }

    }//GEN-LAST:event_btnSearchKeyReleased

