    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        try {

    String supplierIdText = txtSupplierId.getText().trim();
    String amountText = txtAmount.getText().trim();
    String paymentDate = txtPaymentDate.getText().trim();
    String paymentMethod = txtPaymentMethod.getText().trim();
    String referenceNumber = txtReferenceNumber.getText().trim();

    if (supplierIdText.isEmpty()
            || amountText.isEmpty()
            || paymentDate.isEmpty()
            || paymentMethod.isEmpty()
            || referenceNumber.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please fill in all fields."
        );
        return;
    }

    int supplierId = Integer.parseInt(supplierIdText);
    double amount = Double.parseDouble(amountText);

    boolean success =
            dao.SupplierPaymentDao.addSupplierPayment(
                    supplierId,
                    amount,
                    paymentDate,
                    paymentMethod,
                    referenceNumber
            );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Supplier payment added successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblSupplierPayment.getModel();

        dao.SupplierPaymentDao.loadSupplierPayments(model);

        txtSupplierPaymentId.setText("");
        txtSupplierId.setText("");
        txtAmount.setText("");
        txtPaymentDate.setText("");
        txtPaymentMethod.setText("");
        txtReferenceNumber.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not add supplier payment."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Supplier ID and Amount must be numbers."
    );

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        try {

    if (txtSupplierPaymentId.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a payment first."
        );
        return;
    }

    int paymentId =
            Integer.parseInt(txtSupplierPaymentId.getText().trim());

    int confirm =
            javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "Are you sure you want to delete this payment?",
                    "Confirm Delete",
                    javax.swing.JOptionPane.YES_NO_OPTION
            );

    if (confirm != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    boolean success =
            dao.SupplierPaymentDao.deleteSupplierPayment(
                    paymentId
            );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Supplier payment deleted successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblSupplierPayment.getModel();

        dao.SupplierPaymentDao.loadSupplierPayments(model);

        txtSupplierPaymentId.setText("");
        txtSupplierId.setText("");
        txtAmount.setText("");
        txtPaymentDate.setText("");
        txtPaymentMethod.setText("");
        txtReferenceNumber.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Payment could not be deleted."
        );
    }

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnDeleteActionPerformed

