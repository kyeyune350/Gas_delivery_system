    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String orderText = txtOrderId.getText().trim();
String driverText = txtDriverId.getText().trim();
String vehicleText = txtVehicleId.getText().trim();

if (orderText.isEmpty()
        || driverText.isEmpty()
        || vehicleText.isEmpty()
        || txtDeliveryAddress.getText().trim().isEmpty()
        || txtDeliveryDate.getText().trim().isEmpty()
        || txtStatus.getText().trim().isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields."
    );
    return;
}

try {

    boolean success = dao.DeliveryDao.addDelivery(
            Integer.parseInt(orderText),
            Integer.parseInt(driverText),
            Integer.parseInt(vehicleText),
            txtDeliveryAddress.getText().trim(),
            txtDeliveryDate.getText().trim(),
            txtStatus.getText().trim()
    );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Delivery added successfully."
        );

        dao.DeliveryDao.loadDeliveries(
                (javax.swing.table.DefaultTableModel)
                tblDeliveries.getModel()
        );

        txtOrderId.setText("");
        txtDriverId.setText("");
        txtVehicleId.setText("");
        txtDeliveryAddress.setText("");
        txtDeliveryDate.setText("");
        txtStatus.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Delivery could not be added."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Order ID, Driver ID and Vehicle ID must be numbers."
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void tblDeliveriesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDeliveriesMouseClicked
        // TODO add your handling code here:
        int row = tblDeliveries.getSelectedRow();

if (row >= 0) {

    txtDeliveryId.setText(
            tblDeliveries.getValueAt(row, 0).toString()
    );

    txtOrderId.setText(
            tblDeliveries.getValueAt(row, 1).toString()
    );

    txtDriverId.setText(
            tblDeliveries.getValueAt(row, 2).toString()
    );

    txtVehicleId.setText(
            tblDeliveries.getValueAt(row, 3).toString()
    );

    txtDeliveryAddress.setText(
            tblDeliveries.getValueAt(row, 4).toString()
    );

    txtDeliveryDate.setText(
            tblDeliveries.getValueAt(row, 5).toString()
    );

    txtStatus.setText(
            tblDeliveries.getValueAt(row, 6).toString()
    );
}
    }//GEN-LAST:event_tblDeliveriesMouseClicked

