    private void tblOrderItemMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblOrderItemMouseClicked
        // TODO add your handling code here:
        int row = tblOrderItem.getSelectedRow();

if (row >= 0) {

    txtOrderItemId.setText(
            tblOrderItem.getValueAt(row, 0).toString()
    );

    txtOrderId.setText(
            tblOrderItem.getValueAt(row, 1).toString()
    );

    txtProductId.setText(
            tblOrderItem.getValueAt(row, 2).toString()
    );

    txtQuantity.setText(
            tblOrderItem.getValueAt(row, 3).toString()
    );

    txtUnitPrice.setText(
            tblOrderItem.getValueAt(row, 4).toString()
    );

    txtSubtotal.setText(
            tblOrderItem.getValueAt(row, 5).toString()
    );
}
    }//GEN-LAST:event_tblOrderItemMouseClicked

