    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (txtOrderId.getText().trim().isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select an order first."
    );
    return;
}

try {

    int orderId =
            Integer.parseInt(txtOrderId.getText().trim());

    int customerId =
            Integer.parseInt(txtCustomerId.getText().trim());

    int userId =
            Integer.parseInt(txtOrderDate.getText().trim());

    String orderDate =
            txtOrderDate.getText().trim();

    double totalAmount =
            Double.parseDouble(
                    txtTotalAmount.getText().trim()
            );

    String status =
            txtStatus.getText().trim();

    String deliveryAddress =
            txtDeliveryAddress.getText().trim();

    boolean success = dao.OrderDao.updateOrder(
            orderId,
            customerId,
            userId,
            orderDate,
            totalAmount,
            status,
            deliveryAddress
    );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order updated successfully."
        );

        dao.OrderDao.loadOrders(
                (javax.swing.table.DefaultTableModel)
                tblOrders.getModel()
        );

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order could not be updated."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "IDs and Total Amount must be valid numbers."
    );
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String customerText = txtCustomerId.getText().trim();
String userText = txtOrderDate.getText().trim();
String orderDate = txtOrderDate.getText().trim();
String totalText = txtTotalAmount.getText().trim();
String status = txtStatus.getText().trim();
String deliveryAddress = txtDeliveryAddress.getText().trim();

if (customerText.isEmpty()
        || userText.isEmpty()
        || orderDate.isEmpty()
        || totalText.isEmpty()
        || status.isEmpty()
        || deliveryAddress.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields."
    );
    return;
}

try {

    int customerId = Integer.parseInt(customerText);
    int userId = Integer.parseInt(userText);
    double totalAmount = Double.parseDouble(totalText);

    boolean success = dao.OrderDao.addOrder(
            customerId,
            userId,
            orderDate,
            totalAmount,
            status,
            deliveryAddress
    );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order added successfully."
        );

        dao.OrderDao.loadOrders(
                (javax.swing.table.DefaultTableModel)
                tblOrders.getModel()
        );

        txtCustomerId.setText("");
        txtOrderDate.setText("");
        txtOrderDate.setText("");
        txtTotalAmount.setText("");
        txtStatus.setText("");
        txtDeliveryAddress.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order could not be added."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Customer ID, User ID and Total Amount must be valid numbers."
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (txtOrderId.getText().trim().isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select an order first."
    );
    return;
}

int answer = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this order?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (answer == javax.swing.JOptionPane.YES_OPTION) {

    int orderId =
            Integer.parseInt(
                    txtOrderId.getText().trim()
            );

    boolean success =
            dao.OrderDao.deleteOrder(orderId);

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order deleted successfully."
        );

        dao.OrderDao.loadOrders(
                (javax.swing.table.DefaultTableModel)
                tblOrders.getModel()
        );

        txtOrderId.setText("");
        txtCustomerId.setText("");
        txtOrderDate.setText("");
        txtOrderDate.setText("");
        txtTotalAmount.setText("");
        txtStatus.setText("");
        txtDeliveryAddress.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Order could not be deleted."
        );
    }
}
    }//GEN-LAST:event_btnDeleteActionPerformed

