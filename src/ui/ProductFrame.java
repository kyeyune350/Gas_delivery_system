    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String productName = txtProductName.getText().trim();
String description = txtDescription.getText().trim();
String priceText = txtUnitPrice.getText().trim();
String gasType = txtGasType.getText().trim();
String cylinderSize = txtCylinderSize.getText().trim();

if (productName.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the product name."
    );
    txtProductName.requestFocus();
    return;
}

if (priceText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the unit price."
    );
    txtUnitPrice.requestFocus();
    return;
}

if (gasType.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the gas type."
    );
    txtGasType.requestFocus();
    return;
}

if (cylinderSize.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the cylinder size."
    );
    txtCylinderSize.requestFocus();
    return;
}

try {

    double unitPrice = Double.parseDouble(priceText);

    if (unitPrice <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Unit price must be greater than zero."
        );
        txtUnitPrice.requestFocus();
        return;
    }

    boolean added = dao.ProductDao.addProduct(
            productName,
            description,
            unitPrice,
            gasType,
            cylinderSize
    );

    if (added) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Product added successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblProducts.getModel();

        dao.ProductDao.loadProducts(model);

        txtProductId.setText("");
        txtProductName.setText("");
        txtDescription.setText("");
        txtUnitPrice.setText("");
        txtGasType.setText("");
        txtCylinderSize.setText("");

        txtProductName.requestFocus();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not add product.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Unit price must be a valid number.\nExample: 35000"
    );

    txtUnitPrice.requestFocus();
}
    }//GEN-LAST:event_btnAddActionPerformed

