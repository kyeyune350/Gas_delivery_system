    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String orderText = txtOrderId.getText().trim();
String amountText = txtAmount.getText().trim();
String paymentDate = txtPaymentDate.getText().trim();
String paymentMethod = txtPaymentMethod.getText().trim();
String status = txtStatus.getText().trim();
String referenceNumber = txtReferenceNumber.getText().trim();

if (orderText.isEmpty()
        || amountText.isEmpty()
        || paymentDate.isEmpty()
        || paymentMethod.isEmpty()
        || status.isEmpty()
        || referenceNumber.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields."
    );
    return;
}

try {

    int orderId = Integer.parseInt(orderText);
    double amount = Double.parseDouble(amountText);

    boolean success = dao.PaymentDao.addPayment(
            orderId,
            amount,
            paymentDate,
            paymentMethod,
            status,
            referenceNumber
    );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Payment added successfully."
        );

        dao.PaymentDao.loadPayments(
                (javax.swing.table.DefaultTableModel)
                tblPayments.getModel()
        );

        txtOrderId.setText("");
        txtAmount.setText("");
        txtPaymentDate.setText("");
        txtPaymentMethod.setText("");
        txtStatus.setText("");
        txtReferenceNumber.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Payment could not be added."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Order ID and Amount must be valid numbers."
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

