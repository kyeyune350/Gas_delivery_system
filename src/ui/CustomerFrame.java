    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String name = txtName.getText().trim();
String phone = txtPhone.getText().trim();
String email = txtEmail.getText().trim();
String address = txtAddress.getText().trim();

if (name.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the customer name."
    );
    txtName.requestFocus();
    return;
}

if (phone.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the customer phone."
    );
    txtPhone.requestFocus();
    return;
}

if (email.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the customer email."
    );
    txtEmail.requestFocus();
    return;
}

if (address.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the customer address."
    );

    return;
}

boolean added = dao.CustomerDao.addCustomer(
        name,
        phone,
        email,
        address
);

if (added) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Customer added successfully."
    );

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel)
            tblCustomers.getModel();

    dao.CustomerDao.loadCustomers(model);

    txtCustomerId.setText("");
    txtName.setText("");
    txtPhone.setText("");
    txtEmail.setText("");
   

    txtName.requestFocus();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Could not add customer.\n"
            + "Check that the phone or email is not already used.",
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_btnAddActionPerformed

