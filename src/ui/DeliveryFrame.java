    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        if (txtDeliveryId.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a delivery first."
    );
    return;
}

try {

    boolean success = dao.DeliveryDao.updateDelivery(
            Integer.parseInt(txtDeliveryId.getText().trim()),
            Integer.parseInt(txtOrderId.getText().trim()),
            Integer.parseInt(txtDriverId.getText().trim()),
            Integer.parseInt(txtVehicleId.getText().trim()),
            txtDeliveryAddress.getText().trim(),
            txtDeliveryDate.getText().trim(),
            txtStatus.getText().trim()
    );

    if (success) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Delivery updated successfully."
        );

        dao.DeliveryDao.loadDeliveries(
                (javax.swing.table.DefaultTableModel)
                tblDeliveries.getModel()
        );

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Delivery could not be updated."
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "IDs must be valid numbers."
    );
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        if (txtDeliveryId.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a delivery first."
    );
    return;
}

int answer = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this delivery?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (answer == javax.swing.JOptionPane.YES_OPTION) {

    int deliveryId =
            Integer.parseInt(txtDeliveryId.getText().trim());

    if (dao.DeliveryDao.deleteDelivery(deliveryId)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Delivery deleted successfully."
        );

        dao.DeliveryDao.loadDeliveries(
                (javax.swing.table.DefaultTableModel)
                tblDeliveries.getModel()
        );

        txtDeliveryId.setText("");
        txtOrderId.setText("");
        txtDriverId.setText("");
        txtVehicleId.setText("");
        txtDeliveryAddress.setText("");
        txtDeliveryDate.setText("");
        txtStatus.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Delivery could not be deleted."
        );
    }
}
    }//GEN-LAST:event_btnDeleteActionPerformed

