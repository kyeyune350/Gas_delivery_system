    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String warehouseName =
        txtWarehouseName.getText().trim();

String location =
        txtLocation.getText().trim();

String capacityText =
        txtCapacity.getText().trim();

String status =
        txtStatus.getText().trim();

if (warehouseName.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the warehouse name."
    );

    txtWarehouseName.requestFocus();
    return;
}

if (location.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the warehouse location."
    );

    txtLocation.requestFocus();
    return;
}

if (capacityText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the warehouse capacity."
    );

    txtCapacity.requestFocus();
    return;
}

if (status.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter the warehouse status."
    );

    txtStatus.requestFocus();
    return;
}

try {

    int capacity =
            Integer.parseInt(capacityText);

    if (capacity <= 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Capacity must be greater than zero."
        );

        txtCapacity.requestFocus();
        return;
    }

    boolean added =
            dao.WarehouseDao.addWarehouse(
                    warehouseName,
                    location,
                    capacity,
                    status
            );

    if (added) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Warehouse added successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblWarehouses.getModel();

        dao.WarehouseDao.loadWarehouses(model);

        txtWarehouseId.setText("");
        txtWarehouseName.setText("");
        txtLocation.setText("");
        txtCapacity.setText("");
        txtStatus.setText("");

        txtWarehouseName.requestFocus();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not add warehouse.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Capacity must be a whole number."
    );

    txtCapacity.requestFocus();
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        String idText =
        txtWarehouseId.getText().trim();

String warehouseName =
        txtWarehouseName.getText().trim();

String location =
        txtLocation.getText().trim();

String capacityText =
        txtCapacity.getText().trim();

String status =
        txtStatus.getText().trim();

if (idText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a warehouse first."
    );

    return;
}

if (warehouseName.isEmpty()
        || location.isEmpty()
        || capacityText.isEmpty()
        || status.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields."
    );

    return;
}

try {

    int warehouseId =
            Integer.parseInt(idText);

    int capacity =
            Integer.parseInt(capacityText);

    if (capacity <= 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Capacity must be greater than zero."
        );

        return;
    }

    boolean updated =
            dao.WarehouseDao.updateWarehouse(
                    warehouseId,
                    warehouseName,
                    location,
                    capacity,
                    status
            );

    if (updated) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Warehouse updated successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblWarehouses.getModel();

        dao.WarehouseDao.loadWarehouses(model);

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Warehouse was not found.",
                "Update Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Warehouse ID and capacity must be valid numbers."
    );
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        String idText =
        txtWarehouseId.getText().trim();

if (idText.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a warehouse first."
    );

    return;
}

int confirm =
        javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this warehouse?",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

if (confirm != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

try {

    int warehouseId =
            Integer.parseInt(idText);

    boolean deleted =
            dao.WarehouseDao.deleteWarehouse(
                    warehouseId
            );

    if (deleted) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Warehouse deleted successfully."
        );

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel)
                tblWarehouses.getModel();

        dao.WarehouseDao.loadWarehouses(model);

        txtWarehouseId.setText("");
        txtWarehouseName.setText("");
        txtLocation.setText("");
        txtCapacity.setText("");
        txtStatus.setText("");

        tblWarehouses.clearSelection();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Warehouse could not be deleted.",
                "Delete Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid warehouse ID."
    );
}
    }//GEN-LAST:event_btnDeleteActionPerformed

